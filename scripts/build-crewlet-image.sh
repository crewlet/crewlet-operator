#!/usr/bin/env bash
#
# build-crewlet-image.sh — build the Crewlet engine's container image from
# source, at the version the operator is pinned to.
#
#   scripts/build-crewlet-image.sh <version> <image>
#
# <version> is a Go module version of github.com/crewlet/crewlet: a release
# tag (v0.2.0) or a pseudo-version (v0.1.1-0.20261010171839-4e45c6b992a2),
# whose last twelve hex digits name the commit. The Makefile passes
# CREWLET_VERSION, so the image the e2e suite runs is the engine every other
# suite tests against.
#
# Environment:
#   CONTAINER_TOOL  the image builder (default docker)
#
# WHY THE MODULE AND NOT A CLONE: the source is the module zip the Go command
# downloads for <version>, whose hash it checks against the checksum
# database, as it does when `make crewlet` installs the same version. A
# clone of a tag, which can be moved, or of a commit prefix would build an
# engine nothing ties to the one every other suite tests; the module is that
# engine's source, byte for byte. The zip holds everything the build reads:
# the Dockerfile, LICENSE, scripts/notices and static/.
#
# WHY NOT `docker build` IN THE CHECKOUT: crewlet's Dockerfile builds nothing.
# Its release (goreleaser) cross-compiles the binary and stages it, with the
# license and third-party notices, into the build context, and the Dockerfile
# copies them from there. This script stages the same context the same way —
# the binary at linux/<arch>/crewlet, built with the release's flags, and the
# notices generated by crewlet's own generator — and then runs crewlet's
# Dockerfile unchanged on it. A Dockerfile of our own that compiled crewlet
# would test an image nobody ships.
set -euo pipefail

if [ "$#" -ne 2 ]; then
	echo "usage: $0 <crewlet module version> <image>" >&2
	exit 2
fi
version="$1"
image="$2"
tool="${CONTAINER_TOOL:-docker}"

tmp="$(mktemp -d)"
trap 'chmod -R u+w "$tmp"; rm -rf "$tmp"' EXIT

# Outside any module, so that only the checksum database vouches for the
# download: no go.sum of ours is consulted or written. The variables that
# would exempt the module from the database (GOPRIVATE, GONOSUMDB,
# GOINSECURE, GOSUMDB=off, GOFLAGS=-insecure) are cleared; GOPROXY is kept,
# since the database checks whatever proxy served the zip.
dir="$(cd "$tmp" && GOWORK=off GOFLAGS= GOPRIVATE= GONOSUMDB= GOINSECURE= GOSUMDB= \
	go mod download -json "github.com/crewlet/crewlet@$version" | sed -n 's/^[[:space:]]*"Dir": "\(.*\)",$/\1/p')"
if [ -z "$dir" ] || [ ! -f "$dir/go.mod" ]; then
	echo "go mod download github.com/crewlet/crewlet@$version gave no source directory" >&2
	exit 1
fi
echo "Building crewlet $version from $dir"

# The module cache is read-only; the build writes nothing there, but the
# notices generator and go build run in a copy all the same.
mkdir "$tmp/src"
cp -R "$dir/." "$tmp/src"
chmod -R u+w "$tmp/src"

# The image is for the machine that builds it, which is the machine kind runs
# on: the binary is not cross-compiled for any other architecture.
arch="$(go env GOARCH)"
ctx="$tmp/context"
mkdir -p "$ctx/linux/$arch" "$ctx/build/notices" "$ctx/static/dashboard"

# The release's build flags (crewlet's .goreleaser.yaml), with the version
# stamped as the module version, which is what `go install` of the same
# version reports. GOWORK=off: a go.work around the caller must not reach in.
(
	cd "$tmp/src"
	export GOWORK=off CGO_ENABLED=0
	go run ./scripts/notices -out "$ctx/build/notices/THIRD_PARTY_NOTICES.txt" \
		-main ./cmd/crewlet -targets "linux/$arch"
	GOOS=linux GOARCH="$arch" go build -trimpath \
		-ldflags "-s -w -X github.com/crewlet/crewlet/internal/version.value=$version" \
		-o "$ctx/linux/$arch/crewlet" ./cmd/crewlet
)
cp "$tmp/src/LICENSE" "$ctx/LICENSE"
cp "$tmp/src/static/dashboard/THIRD_PARTY_NOTICES.txt" "$ctx/static/dashboard/"
cp "$tmp/src/Dockerfile" "$ctx/Dockerfile"

# Built from inside the context, with the Dockerfile there, so a builder that
# reads ./Dockerfile by default needs no -f.
cd "$ctx"
"$tool" build --platform "linux/$arch" --tag "$image" .
